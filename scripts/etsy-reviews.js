// ============================================================================
// Reviews left on Etsy, mirrored onto the shop's own pages.
// ============================================================================
//
// Etsy gives the rating, the words and the date, and no name: there is no
// buyer name in the API at all, so a review can be shown as a verified Etsy
// buyer and nothing more. The buyer id that does come back is left here on
// purpose rather than written into a file the whole internet can read.
//
// Buyers' own photos are left out too. They belong to the people who took
// them, and a review on Etsy is not permission to republish a photograph
// somewhere else.

const API = "https://openapi.etsy.com/v3/application";

export async function fetchReviews(shopId, apiKey, { limit = 100 } = {}) {
  const res = await fetch(`${API}/shops/${shopId}/reviews?limit=${limit}`, {
    headers: { "x-api-key": apiKey },
  });
  if (!res.ok) {
    throw new Error(`Etsy reviews answered ${res.status}: ${(await res.text()).slice(0, 160)}`);
  }
  const body = await res.json();
  return Array.isArray(body.results) ? body.results : [];
}

// Only what the site needs, and nothing that identifies anybody.
export function tidyReviews(raw, titles = {}) {
  return raw
    .filter((review) => review && typeof review.rating === "number")
    .map((review) => ({
      rating: review.rating,
      text: String(review.review || "").trim(),
      listing_id: review.listing_id ? String(review.listing_id) : "",
      // The piece it was left on, so a quote can say what it is about.
      piece: titles[String(review.listing_id)] || "",
      date: review.create_timestamp
        ? new Date(review.create_timestamp * 1000).toISOString().slice(0, 10)
        : "",
    }))
    .filter((review) => review.text.length > 0)
    .sort((a, b) => (b.date || "").localeCompare(a.date || ""));
}

export function renderReviewsFile(reviews, { syncedAt }) {
  const total = reviews.length;
  const average = total ? reviews.reduce((sum, r) => sum + r.rating, 0) / total : 0;

  const banner = [
    "// ============================================================================",
    "// REVIEWS — what buyers said on Etsy.",
    "// ============================================================================",
    "//",
    "// Auto-generated by scripts/sync-etsy.js. Do not hand-edit.",
    "//",
    "// No names and no buyer photos: Etsy does not provide a name, and the photos",
    "// belong to the buyers who took them.",
    "//",
    `// Last read from Etsy: ${syncedAt}`,
    "",
  ].join("\n");

  return (
    banner +
    `window.MICKNACK_REVIEWS = ${JSON.stringify(
      {
        count: total,
        average: Number(average.toFixed(2)),
        five_star: reviews.filter((r) => r.rating === 5).length,
        shop_reviews_url: "https://www.etsy.com/shop/MicknackStacks/reviews",
        reviews,
      },
      null,
      2
    )};\n`
  );
}
