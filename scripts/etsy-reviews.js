// ============================================================================
// Reviews left on Etsy, mirrored onto the shop's own pages.
// ============================================================================
//
// Etsy gives the rating, the words and the date, and no name: there is no
// buyer name in the API at all, so a review can be shown as a verified Etsy
// buyer and nothing more. The buyer id that does come back is left here on
// purpose rather than written into a file the whole internet can read.
//
// Buyers' photos ARE mirrored, at Jamie's say-so after being asked. They are
// copied into assets/reviews and served from here rather than hotlinked, so a
// photo cannot vanish when Etsy tidies its CDN. Nothing identifying travels
// with them: a file is named after Etsy's own id for the image, never after
// the buyer or their order.

import { existsSync, mkdirSync, writeFileSync, readdirSync } from "node:fs";
import { join } from "node:path";

const API = "https://openapi.etsy.com/v3/application";

// Where the mirrored photos live. Two spellings on purpose: one for the disk,
// which is backslashed on Windows, and one for the page, which never is.
const PHOTO_DIR = join("assets", "reviews");
const PHOTO_PATH = "assets/reviews";

// Etsy's own id for the image, taken from its URL:
//   .../iap_fullxfull.8955383427_lmwy8vpq.jpg?version=0  ->  8955383427_lmwy8vpq
// Stable between syncs, so a photo is fetched once and then left alone, and
// it says nothing about who left the review.
function photoName(url) {
  const match = String(url).match(/iap_fullxfull\.([A-Za-z0-9_]+)\.(jpe?g|png|webp)/i);
  if (!match) return "";
  return `${match[1]}.${match[2].toLowerCase()}`;
}

// Fetches every review photo that is not already on disk. Returns a map of
// Etsy URL to the path the site should use.
//
// A photo that will not download is simply left out: a review without its
// picture is still a review, and a broken image is worse than none.
export async function mirrorReviewPhotos(raw, root) {
  const dir = join(root, PHOTO_DIR);
  mkdirSync(dir, { recursive: true });
  const have = new Set(existsSync(dir) ? readdirSync(dir) : []);

  const paths = {};
  let fetched = 0;
  let failed = 0;

  for (const review of raw) {
    const url = review && review.image_url_fullxfull;
    if (!url) continue;
    const name = photoName(url);
    if (!name) continue;

    const webPath = `${PHOTO_PATH}/${name}`;
    paths[url] = webPath;
    if (have.has(name)) continue;

    try {
      const res = await fetch(url);
      if (!res.ok) throw new Error(`answered ${res.status}`);
      writeFileSync(join(dir, name), Buffer.from(await res.arrayBuffer()));
      have.add(name);
      fetched++;
    } catch (err) {
      console.log(`::warning::Could not fetch a review photo: ${err.message}`);
      delete paths[url];
      failed++;
    }
  }

  return { paths, fetched, failed, total: Object.keys(paths).length };
}

export async function fetchReviews(shopId, apiKey, { limit = 100 } = {}) {
  const res = await fetch(`${API}/shops/${shopId}/reviews?limit=${limit}`, {
    headers: { "x-api-key": apiKey },
  });
  if (!res.ok) {
    throw new Error(`Etsy reviews answered ${res.status}: ${(await res.text()).slice(0, 160)}`);
  }
  const body = await res.json();
  return Array.isArray(body.results) ? body.results : [];
}

// Only what the site needs, and nothing that identifies anybody.
//
// `photos` maps an Etsy photo URL to where that photo now lives here; it comes
// from mirrorReviewPhotos. Without it the reviews are simply text, which is
// what they were before.
export function tidyReviews(raw, titles = {}, photos = {}) {
  return raw
    .filter((review) => review && typeof review.rating === "number")
    .map((review) => ({
      rating: review.rating,
      text: String(review.review || "").trim(),
      photo: photos[review.image_url_fullxfull] || "",
      listing_id: review.listing_id ? String(review.listing_id) : "",
      // The piece it was left on, so a quote can say what it is about.
      piece: titles[String(review.listing_id)] || "",
      date: review.create_timestamp
        ? new Date(review.create_timestamp * 1000).toISOString().slice(0, 10)
        : "",
    }))
    .filter((review) => review.text.length > 0)
    .sort((a, b) => (b.date || "").localeCompare(a.date || ""));
}

export function renderReviewsFile(reviews, { syncedAt }) {
  const total = reviews.length;
  const average = total ? reviews.reduce((sum, r) => sum + r.rating, 0) / total : 0;

  const banner = [
    "// ============================================================================",
    "// REVIEWS — what buyers said on Etsy.",
    "// ============================================================================",
    "//",
    "// Auto-generated by scripts/sync-etsy.js. Do not hand-edit.",
    "//",
    "// No names: Etsy does not provide one, so a review can only ever say it",
    "// came from a verified Etsy buyer.",
    "//",
    "// Buyers' photos are mirrored into assets/reviews and referenced by path.",
    "//",
    `// Last read from Etsy: ${syncedAt}`,
    "",
  ].join("\n");

  return (
    banner +
    `window.MICKNACK_REVIEWS = ${JSON.stringify(
      {
        count: total,
        average: Number(average.toFixed(2)),
        five_star: reviews.filter((r) => r.rating === 5).length,
        shop_reviews_url: "https://www.etsy.com/shop/MicknackStacks/reviews",
        reviews,
      },
      null,
      2
    )};\n`
  );
}
